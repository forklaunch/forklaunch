use anyhow::{Result, bail};
use clap::{Arg, ArgAction, ArgMatches, Command};

use super::rust_project;
use crate::{CliCommand, constants::Database, core::command::command};

#[derive(Debug)]
pub(crate) struct AgentCommand;

impl AgentCommand {
    pub(crate) fn new() -> Self {
        Self {}
    }
}

impl CliCommand for AgentCommand {
    fn command(&self) -> Command {
        command("agent", "Initialize a new agent")
            .alias("agt")
            .arg(Arg::new("name").help("The name of the agent"))
            .arg(
                Arg::new("base_path")
                    .short('p')
                    .long("path")
                    .help("The application path to initialize the agent in"),
            )
            .arg(
                Arg::new("language")
                    .long("language")
                    .help("Project language to generate")
                    .value_parser(rust_project::PROJECT_LANGUAGE_VARIANTS)
                    .default_value("typescript"),
            )
            .arg(
                Arg::new("description")
                    .short('D')
                    .long("description")
                    .help("The description of the agent"),
            )
            .arg(
                Arg::new("instructions")
                    .long("instructions")
                    .help("System instructions for the model (default: a safe read-only assistant)"),
            )
            .arg(
                Arg::new("services")
                    .long("service")
                    .help("Expose this app service's routes as tools (repeatable)")
                    .action(ArgAction::Append),
            )
            .arg(
                Arg::new("mcp_servers")
                    .long("mcp")
                    .value_name("name=url")
                    .help("External MCP server over streamable HTTP, as <name>=<url> (repeatable)")
                    .action(ArgAction::Append),
            )
            .arg(
                Arg::new("database")
                    .short('d')
                    .long("database")
                    .help("Optional database for the agent")
                    .value_parser(Database::VARIANTS),
            )
            // Read by the shared service generator; agents never set them.
            .arg(Arg::new("infrastructure").long("infrastructure").hide(true).action(ArgAction::Append))
            .arg(Arg::new("mappers").long("mappers").hide(true).action(ArgAction::SetTrue))
            .arg(
                Arg::new("dryrun")
                    .short('n')
                    .long("dryrun")
                    .help("Dry run the command")
                    .action(ArgAction::SetTrue),
            )
    }

    fn handler(&self, matches: &ArgMatches) -> Result<()> {
        if rust_project::uses_rust_generation(matches) {
            return rust_project::generate_rust_agent(matches);
        }
        bail!("TypeScript agents are generated by the TypeScript `init agent`; use --language rust here")
    }
}
