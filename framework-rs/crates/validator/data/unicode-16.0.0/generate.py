#!/usr/bin/env python3
"""Generate default Unicode16 casing; verify every source byte before parsing.

Optional first argument is a directory containing UnicodeData.txt and
DerivedCoreProperties.txt. The repository default reuses retained vendor inputs.
"""
import hashlib
from pathlib import Path
import sys

here = Path(__file__).resolve().parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else here.parents[2] / 'vendor/regress/unicode-16.0.0'
checks = {
    'UnicodeData.txt': 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f',
    'DerivedCoreProperties.txt': '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd',
    'SpecialCasing.txt': '8d5de354eef79f2395a54c9c7dcebbaf3d30fc962d0f85611ea97aa973a0c451',
}
data = {}
for name, digest in checks.items():
    raw = ((here if name == 'SpecialCasing.txt' else source) / name).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == digest, name
    data[name] = raw.decode('utf-8')
lower, upper = {}, {}
for row in data['UnicodeData.txt'].splitlines():
    f = row.split(';')
    cp = int(f[0], 16)
    for table, index in [(upper, 12), (lower, 13)]:
        if f[index]:
            table[cp] = [int(f[index], 16)]
conditional = []
for row in data['SpecialCasing.txt'].splitlines():
    raw = row.split('#')[0].strip()
    if not raw:
        continue
    f = [part.strip() for part in raw.split(';')]
    if f[4]:
        if not any(lang in f[4].split() for lang in ['tr', 'az', 'lt']):
            conditional.append((f[0], f[4]))
        continue
    for table, index in [(lower, 1), (upper, 3)]:
        table[int(f[0], 16)] = [int(cp, 16) for cp in f[index].split()]
assert conditional == [('03A3', 'Final_Sigma')]
properties = {'Cased': [], 'Case_Ignorable': []}
for row in data['DerivedCoreProperties.txt'].splitlines():
    f = [part.strip() for part in row.split('#')[0].split(';')]
    if len(f) < 2 or f[1] not in properties:
        continue
    bounds = [int(cp, 16) for cp in f[0].split('..')]
    properties[f[1]].append((bounds[0], bounds[-1]))
lines = ['// Generated by data/unicode-16.0.0/generate.py; do not edit.', '// Unicode16 default case mapping. See retained Unicode License V3.']
for name, table in [('LOWER', lower), ('UPPER', upper)]:
    lines.extend(['#[rustfmt::skip]', f'pub(super) static {name}: &[(u32, &str)] = &['])
    for cp, mapped in sorted(table.items()):
        value = ''.join('\\u{' + format(ch, 'x') + '}' for ch in mapped)
        lines.append(f'    (0x{cp:x}, "{value}"),')
    lines.append('];')
for name, ranges in properties.items():
    lines.extend(['#[rustfmt::skip]', f'pub(super) static {name.upper()}: &[(u32, u32)] = &['])
    for lo, hi in ranges:
        lines.append(f'    (0x{lo:x}, 0x{hi:x}),')
    lines.append('];')
(here.parents[1] / 'src/zod_string_case_tables.rs').write_text('\n'.join(lines) + '\n')
print(f'Unicode16 casing: {len(lower)} lower, {len(upper)} upper, {sum(map(len, properties.values()))} context ranges')
