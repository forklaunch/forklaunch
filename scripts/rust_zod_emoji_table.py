#!/usr/bin/env python3
"""Reproduce the pinned raw-Zod Unicode16 emoji union; default checks committed output."""
import argparse
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / "framework-rs/crates/common/data/unicode-16.0.0/emoji-data.txt"
target = root / "framework-rs/crates/common/src/zod_string_format/emoji_table.rs"
assert hashlib.sha256(source.read_bytes()).hexdigest() == "f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a"
ranges = []
for line in source.read_text().splitlines():
    value = line.split("#", 1)[0].strip()
    if not value:
        continue
    code, prop = (part.strip() for part in value.split(";"))
    if prop not in {"Extended_Pictographic", "Emoji_Component"}:
        continue
    bounds = code.split("..")
    ranges.append((int(bounds[0], 16), int(bounds[-1], 16)))
merged = []
for start, end in sorted(ranges):
    if merged and start <= merged[-1][1] + 1:
        merged[-1] = (merged[-1][0], max(end, merged[-1][1]))
    else:
        merged.append((start, end))
text = "// Generated by scripts/rust_zod_emoji_table.py; do not edit.\n// Unicode16 Extended_Pictographic | Emoji_Component.\n// Source/license: ../../data/unicode-16.0.0/\npub(super) const RANGES: &[(u32, u32)] = &[\n"
text += "".join(f"    ({start:_}, {end:_}),\n" for start, end in merged) + "];\n"
args = argparse.ArgumentParser()
args.add_argument("--write", action="store_true")
write = args.parse_args().write
if write:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
else:
    assert target.read_text() == text, "Emoji table differs; run with --write"
ts = "// BEGIN GENERATED UNICODE16 EMOJI RANGES\nconst zodEmojiRanges: readonly (readonly [number, number])[] = [\n"
ts += "".join(f"  [{start}, {end}],\n" for start, end in merged)
ts += "];\n// END GENERATED UNICODE16 EMOJI RANGES"
for relative in ["framework/universal-sdk/src/core/zodChecks.ts", "framework-rs/crates/core/src/typescript/zod-checks.ts"]:
    helper = root / relative
    content = helper.read_text()
    begin = content.index("// BEGIN GENERATED UNICODE16 EMOJI RANGES")
    end = content.index("// END GENERATED UNICODE16 EMOJI RANGES") + len("// END GENERATED UNICODE16 EMOJI RANGES")
    expected = content[:begin] + ts + content[end:]
    if write:
        helper.write_text(expected)
    else:
        assert content == expected, f"Emoji helper table differs: {relative}"
print(f"PASS pinned Unicode16 emoji union: {len(merged)} ranges")
